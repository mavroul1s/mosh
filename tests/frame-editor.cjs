const assert=require('node:assert/strict');require('../codec.js');const {PacketEditor}=require('../frame-editor.js');
const header=new Uint8Array(68);header.set(Buffer.from('hdrlavih'));new DataView(header.buffer).setUint32(8,56,true);
const packet=(type,n)=>({type,data:Uint8Array.of(0,0,1,182,({I:0,P:1,B:2}[type]<<6),n)});
const avi=AVI.build(header,[packet('I',0),packet('P',1),packet('B',2),packet('I',3)]);
const m=new PacketEditor(avi,24);
assert.equal(new PacketEditor(avi.buffer,24).frames.length,4,'worker ArrayBuffer results are accepted');
assert.deepEqual(m.frames.map(f=>f.type),['I','P','B','I']);
const original=m.frames.map(f=>f.data);m.remove(1);assert.deepEqual(m.frames.map(f=>f.type),['I','B','I']);
assert.equal(AVI.parse(m.save()).frames.length,3);
assert(m.undo());assert.deepEqual(m.frames.map(f=>f.data),original);assert(!m.dirty);
assert(m.redo());assert(m.dirty);m.undo();
const donor=m.frames[2];m.replace(1,donor);assert.equal(m.frames[1].type,'B');assert.deepEqual(m.frames[1].data,donor.data);
assert.deepEqual(AVI.parse(m.save()).frames.map(f=>f.type),['I','B','B','I']);
m.undo();assert.equal(m.frames[1].type,'P');m.redo();assert.equal(m.frames[1].type,'B');
m.undo();m.remove(3);assert.equal(m.redoStack.length,0,'new edits invalidate redo');
assert.throws(()=>m.replace(0,null),/replacement/);
const one=new PacketEditor(AVI.build(header,[packet('I',0)]));assert.throws(()=>one.remove(0),/at least one/);
const mapped=new PacketEditor(avi);mapped.setPositions([mapped.frames[0].pos,mapped.frames[2].pos,mapped.frames[1].pos,mapped.frames[3].pos]);assert.equal(mapped.previewMap.get(mapped.frames[2].id),1,'B frame uses decoded display position');
console.log('PASS: I/P/B packet editing, raw AVI export, immutable donor copy, undo/redo, last-frame guard, B-frame display map');
